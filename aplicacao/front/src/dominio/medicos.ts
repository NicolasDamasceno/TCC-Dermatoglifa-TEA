/** Mesmas regras de senha do Identity no back (InjecaoDeDependencia: 10+, dígito, minúscula). */
export const REGRA_SENHA = 'Pelo menos 10 caracteres, com uma letra minúscula e um número.';

export function problemaDaSenha(senha: string): string | undefined {
  if (senha.length < 10) return 'A senha deve ter pelo menos 10 caracteres.';
  if (!/\p{Ll}/u.test(senha)) return 'A senha deve conter pelo menos uma letra minúscula.';
  if (!/\p{Nd}/u.test(senha)) return 'A senha deve conter pelo menos um número.';
  return undefined;
}
